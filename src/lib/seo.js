// Update DOM head tags for single page routing
export function applyRouteSEO(pathname) {
  const normalizedPath = Object.keys(PAGE_SEO_DATA).includes(pathname) ? pathname : '/'
  const seo = PAGE_SEO_DATA[normalizedPath] || PAGE_SEO_DATA['/']

  // Update Title
  document.title = seo.title

  // Update Meta Title & Description
  let metaTitle = document.querySelector('meta[name="title"]')
  if (metaTitle) metaTitle.setAttribute('content', seo.title)

  let metaDesc = document.querySelector('meta[name="description"]')
  if (metaDesc) metaDesc.setAttribute('content', seo.description)

  let metaKw = document.querySelector('meta[name="keywords"]')
  if (metaKw) metaKw.setAttribute('content', seo.keywords)

  // Update Canonical
  let canonicalTag = document.querySelector('link[rel="canonical"]')
  if (canonicalTag) {
    canonicalTag.setAttribute('href', seo.canonical)
  }

  // Update OpenGraph
  let ogTitle = document.querySelector('meta[property="og:title"]')
  if (ogTitle) ogTitle.setAttribute('content', seo.title)

  let ogDesc = document.querySelector('meta[property="og:description"]')
  if (ogDesc) ogDesc.setAttribute('content', seo.description)

  let ogUrl = document.querySelector('meta[property="og:url"]')
  if (ogUrl) ogUrl.setAttribute('content', seo.canonical)

  let ogImage = document.querySelector('meta[property="og:image"]')
  if (ogImage) ogImage.setAttribute('content', seo.ogImage)

  // Update Twitter
  let twTitle = document.querySelector('meta[name="twitter:title"]')
  if (twTitle) twTitle.setAttribute('content', seo.title)

  let twDesc = document.querySelector('meta[name="twitter:description"]')
  if (twDesc) twDesc.setAttribute('content', seo.description)

  let twImage = document.querySelector('meta[name="twitter:image"]')
  if (twImage) twImage.setAttribute('content', seo.ogImage)
}
